import type { MatterModuleDemo } from '@/types/matter'

function detail(
  id: string,
  title: string,
  basic: Array<[string, string]>,
  businessStatus: Array<[string, string]>,
  keyMetrics: Array<[string, string]>,
  docs: Array<[string, string, string]>,
  logs: Array<[string, string, string, string]>,
) {
  return {
    id,
    title,
    basic: basic.map(([label, value]) => ({ label, value })),
    businessStatus: businessStatus.map(([label, value]) => ({ label, value })),
    keyMetrics: keyMetrics.map(([label, value]) => ({ label, value })),
    relatedDocs: docs.map(([name, kind, status]) => ({ name, kind, status })),
    operationLogs: logs.map(([at, action, operator, remark]) => ({ at, action, operator, remark })),
  }
}

